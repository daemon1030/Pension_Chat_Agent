def apply(document_number: int, title: str, category: str, topic: str, pages: list[str], facts: dict[int, list[dict]]) -> None:
    path = BASE / f"DOC_{document_number:03d}_structured.json"
    document = json.loads(path.read_text(encoding="utf-8"))
    document["document_meta"].update({"title": title, "category": category})
    for index, section in enumerate(document["sections"]):
        section["source_text"] = pages[index]
        section["section_title"] = pages[index].splitlines()[0]
        section["topic"] = topic
        section["structured_facts"] = facts.get(index + 1, [])
        section["review_required"] = True
    path.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


